/**
 * The shape `config/protobuf.ts` returns: where the schemas come from.
 *
 *   import { defineConfig } from "@c9up/neutrino"
 *   import { file_echo } from "#generated/echo_pb.js"
 *
 *   export default defineConfig({
 *     descriptorSets: [app.makePath("proto/app.binpb")],
 *     files: [file_echo],
 *   })
 */

import type { DescFile } from "@bufbuild/protobuf";

export interface ProtobufConfig {
	/**
	 * Paths of binary `FileDescriptorSet`s, as `buf build -o <file>.binpb` or
	 * `protoc --include_imports --descriptor_set_out=<file>` write them.
	 */
	descriptorSets?: readonly string[];
	/** File descriptors generated by `protoc-gen-es` (its `file_*` exports). */
	files?: readonly DescFile[];
}

/** Type helper for `config/protobuf.ts`; refuses a config that loads nothing. */
export function defineConfig(config: ProtobufConfig): ProtobufConfig {
	const count =
		(config.descriptorSets?.length ?? 0) + (config.files?.length ?? 0);
	if (count === 0) {
		throw new Error(
			"[protobuf] config declares no schema — give descriptorSets or files",
		);
	}
	return config;
}
