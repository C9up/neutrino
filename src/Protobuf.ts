/**
 * The loaded schemas, and the codec over them.
 *
 *   const protobuf = new Protobuf({ files: [file_echo] })
 *   const bytes = protobuf.encode(SayRequestSchema, create(SayRequestSchema, { text: "hi" }))
 *   const request = protobuf.decode(SayRequestSchema, bytes)
 *
 * Messages are `@bufbuild/protobuf` messages: build them with its `create()`,
 * type them with the schemas `protoc-gen-es` generates. Neutrino adds what a
 * server needs on top — schemas from several sources merged without a silent
 * override, lookup by type name and by gRPC method path, and decode failures
 * reported as one error a transport can map to a client error.
 */

import {
	clone,
	createFileRegistry,
	createRegistry,
	type DescFile,
	type DescMessage,
	type DescMethod,
	type DescService,
	fromBinary,
	type MessageShape,
	type Registry,
	toBinary,
} from "@bufbuild/protobuf";
import {
	type FileDescriptorProto,
	FileDescriptorProtoSchema,
	FileDescriptorSetSchema,
} from "@bufbuild/protobuf/wkt";
import {
	DuplicateTypeError,
	InvalidDescriptorError,
	InvalidMessageError,
	UnknownMethodError,
	UnknownTypeError,
} from "./errors.js";

export interface ProtobufSources {
	/**
	 * Binary `FileDescriptorSet`s, as `buf build -o <file>.binpb` or
	 * `protoc --include_imports --descriptor_set_out=<file>` write them.
	 */
	descriptorSets?: readonly Uint8Array[];
	/** File descriptors generated by `protoc-gen-es` (its `file_*` exports). */
	files?: readonly DescFile[];
}

export class Protobuf {
	readonly #registry: Registry;

	constructor(sources: ProtobufSources) {
		const sourced: Sourced[] = [];
		(sources.descriptorSets ?? []).forEach((bytes, index) => {
			const source = `descriptor set #${index}`;
			sourced.push({ source, registry: readDescriptorSet(bytes, source) });
		});
		(sources.files ?? []).forEach((file, index) => {
			sourced.push({
				source: `file #${index}`,
				registry: createRegistry(file),
			});
		});
		rejectConflicts(sourced);
		this.#registry = createRegistry(...sourced.map((s) => s.registry));
	}

	/** The schema of a message type, by its full name (`package.Message`). */
	message(typeName: string): DescMessage {
		const schema = this.#registry.getMessage(typeName);
		if (!schema) throw new UnknownTypeError(typeName);
		return schema;
	}

	/** A service, by its full name (`package.Service`). */
	service(typeName: string): DescService {
		const service = this.#registry.getService(typeName);
		if (!service) throw new UnknownTypeError(typeName, "service");
		return service;
	}

	/**
	 * The method a gRPC request path names — `/package.Service/Method`, exactly
	 * as it arrives on the wire. Its `input` and `output` are the schemas to
	 * decode the request and encode the reply with.
	 */
	method(path: string): DescMethod {
		const match = /^\/([^/]+)\/([^/]+)$/.exec(path);
		const service = match?.[1];
		const name = match?.[2];
		if (service === undefined || name === undefined) {
			throw new UnknownMethodError(path);
		}
		const method = this.#registry
			.getService(service)
			?.methods.find((candidate) => candidate.name === name);
		if (!method) throw new UnknownMethodError(path);
		return method;
	}

	/** Decode bytes received from a client. */
	decode<Desc extends DescMessage>(
		schema: Desc,
		bytes: Uint8Array,
	): MessageShape<Desc> {
		try {
			return fromBinary(schema, bytes);
		} catch (error) {
			throw new InvalidMessageError(schema.typeName, { cause: error });
		}
	}

	/** Encode a message for the wire. */
	encode<Desc extends DescMessage>(
		schema: Desc,
		message: MessageShape<Desc>,
	): Uint8Array {
		return toBinary(schema, message);
	}
}

interface Sourced {
	/** Where the schemas came from, in the order the sources were given. */
	source: string;
	registry: Registry;
}

function readDescriptorSet(bytes: Uint8Array, source: string): Registry {
	try {
		return createFileRegistry(fromBinary(FileDescriptorSetSchema, bytes));
	} catch (error) {
		throw new InvalidDescriptorError(source, { cause: error });
	}
}

/**
 * Throw on a type two sources declare differently. Each type is traced to the
 * file that declares it; the same file twice is fine as long as it is the same
 * file, compared on its serialized descriptor — less what says nothing about
 * the wire (see {@link schemaBytes}).
 */
function rejectConflicts(sourced: readonly Sourced[]): void {
	const seen = new Map<string, { origin: string; proto: Uint8Array }>();
	for (const { source, registry } of sourced) {
		for (const type of registry) {
			const origin = `${type.file.proto.name} (${source})`;
			const proto = schemaBytes(type.file.proto);
			const previous = seen.get(type.typeName);
			if (previous === undefined) {
				seen.set(type.typeName, { origin, proto });
			} else if (!sameBytes(previous.proto, proto)) {
				throw new DuplicateTypeError(type.typeName, previous.origin, origin);
			}
		}
	}
}

/**
 * A file descriptor serialized without what says nothing about the wire: the
 * source info (positions and comments of the `.proto`), and the unknown fields
 * of the file itself. `buf build` keeps both by default — the second is its
 * image extension, field 8042 — where `protoc --descriptor_set_out` and
 * `protoc-gen-es` keep neither. The same `.proto` through two of those tools
 * must not read as two different schemas.
 */
function schemaBytes(proto: FileDescriptorProto): Uint8Array {
	const copy = clone(FileDescriptorProtoSchema, proto);
	copy.sourceCodeInfo = undefined;
	copy.$unknown = undefined;
	return toBinary(FileDescriptorProtoSchema, copy);
}

function sameBytes(a: Uint8Array, b: Uint8Array): boolean {
	if (a.length !== b.length) return false;
	for (let i = 0; i < a.length; i++) {
		if (a[i] !== b[i]) return false;
	}
	return true;
}
