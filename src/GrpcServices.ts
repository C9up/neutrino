/**
 * gRPC services implemented in TypeScript.
 *
 *   grpc.service(EchoService, {
 *     async say(request, context) {
 *       return { text: request.text.repeat(request.times) }
 *     },
 *   })
 *
 * Registered services are served by {@link GrpcServices.handle}, the function
 * the host's server calls for every gRPC call — in a Ream application,
 * `server.grpc(...)`, which the provider wires. Each call arrives as bytes:
 * the request is decoded with the method's input schema, the reply encoded
 * with its output schema.
 *
 * Unary methods only, for now: a service whose implementation names a
 * streaming method is refused when it is registered, and a call to a
 * streaming method answers UNIMPLEMENTED.
 */

import {
	create,
	type DescMethod,
	type DescService,
	type Message,
	type MessageInitShape,
	type MessageShape,
} from "@bufbuild/protobuf";
import {
	InvalidMetadataError,
	NeutrinoError,
	UnknownMethodError,
} from "./errors.js";
import { GrpcMetadata } from "./GrpcMetadata.js";
import type { Protobuf } from "./Protobuf.js";

/** gRPC status codes. */
export const GrpcStatus = {
	OK: 0,
	CANCELLED: 1,
	UNKNOWN: 2,
	INVALID_ARGUMENT: 3,
	DEADLINE_EXCEEDED: 4,
	NOT_FOUND: 5,
	ALREADY_EXISTS: 6,
	PERMISSION_DENIED: 7,
	RESOURCE_EXHAUSTED: 8,
	FAILED_PRECONDITION: 9,
	ABORTED: 10,
	OUT_OF_RANGE: 11,
	UNIMPLEMENTED: 12,
	INTERNAL: 13,
	UNAVAILABLE: 14,
	DATA_LOSS: 15,
	UNAUTHENTICATED: 16,
} as const;

export type GrpcStatusCode = (typeof GrpcStatus)[keyof typeof GrpcStatus];

/**
 * Thrown by a method implementation to answer a status instead of a reply.
 * Its message is sent to the client as the status details; any other error
 * is answered INTERNAL and its message is NOT sent.
 */
export class GrpcError extends NeutrinoError {
	readonly status: GrpcStatusCode;

	constructor(status: GrpcStatusCode, message: string, options?: ErrorOptions) {
		super("E_NEUTRINO_GRPC_STATUS", message, options);
		this.status = status;
	}
}

/** One call as the host's server hands it over. */
export interface GrpcCall {
	/** `/package.Service/Method`. */
	path: string;
	/**
	 * The request headers, a repeated one as a list (a host that keeps only
	 * one value per name gives strings). Transport headers are left out of
	 * what the method sees; see {@link GrpcMetadata}.
	 */
	metadata: Readonly<Record<string, string | readonly string[]>>;
	/** The request message, still encoded. */
	message: Uint8Array;
	/** Resolved client IP. */
	ip: string;
	/**
	 * Aborted by the host when the client cancels the call or its connection
	 * drops. The call is then answered CANCELLED and the method's own
	 * {@link GrpcContext.signal} aborted.
	 */
	signal?: AbortSignal;
}

/** A reply message, encoded — or a status instead of one. */
export type GrpcReply =
	| { message: Uint8Array }
	| { code: number; details: string };

/** What a method implementation receives beside the request. */
export interface GrpcContext {
	/** Request metadata — `authorization` and the like. */
	readonly metadata: GrpcMetadata;
	/** Resolved client IP. */
	readonly ip: string;
	/** The method being called. */
	readonly method: DescMethod;
	/**
	 * When the client stops waiting, in epoch milliseconds — from its
	 * `grpc-timeout`; `Infinity` when it set none. Past it the call is
	 * answered DEADLINE_EXCEEDED.
	 */
	readonly deadline: number;
	/**
	 * Aborted when the call is answered without the method: its deadline
	 * passed, or the client cancelled it. Hand it to the database or HTTP
	 * call the method waits on. Its `reason` is a {@link GrpcError}.
	 */
	readonly signal: AbortSignal;
}

/**
 * A method's implementation. A generated method carries its kind as a
 * literal, so a streaming one gets `never`; a method from a descriptor set
 * carries the union of kinds and stays implementable — registration then
 * checks the kind at runtime.
 */
type UnaryImpl<M> = M extends {
	methodKind: infer Kind;
	input: infer I extends DescMethod["input"];
	output: infer O extends DescMethod["output"];
}
	? "unary" extends Kind
		? (
				request: MessageShape<I>,
				context: GrpcContext,
			) => Promise<MessageInitShape<O>> | MessageInitShape<O>
		: never
	: never;

/**
 * The implementation of a service: one function per method, keyed by the
 * method's local name (`say` for `rpc Say`) — an object literal or a class
 * instance. A method left out answers UNIMPLEMENTED. With a service
 * generated by `protoc-gen-es`, requests and replies are typed from the
 * `.proto`; with one from a descriptor set, nothing is known about its
 * methods until runtime, so any object is accepted and registration checks it.
 */
export type ServiceImpl<S extends DescService> =
	string extends keyof S["method"]
		? // The record gives an object literal's functions their parameter
			// types; `object` admits a class instance, which has no index
			// signature to match the record with.
			Partial<Record<string, UntypedMethod>> | object
		: { [K in keyof S["method"]]?: UnaryImpl<S["method"][K]> };

/**
 * Runs around every call it is registered for, before the request is even
 * decoded — the gRPC form of a middleware. Refuse the call by throwing a
 * {@link GrpcError}; let it through by returning what `next()` returns. Pass
 * a value on to the method with a {@link GrpcContextKey}.
 */
export type GrpcInterceptor = (
	context: GrpcContext,
	next: () => Promise<unknown>,
) => Promise<unknown>;

export interface ServiceOptions {
	/** Run after the interceptors given to `use()`, in this order. */
	interceptors?: readonly GrpcInterceptor[];
}

/** A method of a service known only from a descriptor set. */
export type UntypedMethod = (
	request: Message,
	context: GrpcContext,
) => Promise<Record<string, unknown>> | Record<string, unknown>;

/** A function, called with arguments it is not told the types of. */
function isCallable(
	value: unknown,
): value is (this: unknown, ...args: unknown[]) => unknown {
	return typeof value === "function";
}

function isRecord(value: unknown): value is Record<string, unknown> {
	return typeof value === "object" && value !== null;
}

/**
 * The objects an implementation's members are read from: the object, then
 * its prototypes — a class instance keeps its methods there, out of reach of
 * Object.entries — but never Object.prototype or Function.prototype:
 * protobuf-es leaves `rpc HasOwnProperty` as `hasOwnProperty`, which every
 * object would otherwise "implement".
 */
function ownersOf(impl: object): object[] {
	const owners: object[] = [];
	for (
		let owner: object | null = impl;
		owner !== null &&
		owner !== Object.prototype &&
		owner !== Function.prototype;
		owner = Reflect.getPrototypeOf(owner)
	) {
		owners.push(owner);
	}
	return owners;
}

/** The member `name` of an implementation, read where a method may live. */
function implementationOf(impl: object, name: string): unknown {
	return ownersOf(impl).some((owner) => Object.hasOwn(owner, name))
		? Reflect.get(impl, name)
		: undefined;
}

/**
 * Every name an implementation offers a function under, found where
 * {@link implementationOf} looks: its own keys, enumerable or not, and those
 * of its prototypes, but not the `constructor` a class prototype carries.
 */
function functionNamesOf(impl: object): Set<string> {
	const names = new Set<string>();
	for (const owner of ownersOf(impl)) {
		for (const key of Object.getOwnPropertyNames(owner)) {
			if (owner !== impl && key === "constructor") continue;
			if (isCallable(Reflect.get(impl, key))) names.add(key);
		}
	}
	return names;
}

/** The longest delay a timer holds; a longer one would fire at once. */
const MAX_TIMER_MS = 2 ** 31 - 1;

/** `grpc-timeout`: at most 8 digits and a unit, nothing else. */
const TIMEOUT = /^(\d{1,8})([HMSmun])$/;
const TIMEOUT_UNIT_MS = new Map([
	["H", 3_600_000],
	["M", 60_000],
	["S", 1000],
	["m", 1],
	["u", 0.001],
	["n", 0.000_001],
]);

/**
 * The call's `grpc-timeout`, in whole milliseconds rounded up — a deadline
 * still in the future must not read as already passed. Its first value, as a
 * gRPC server reads it.
 */
function timeoutOf(headers: GrpcCall["metadata"]): {
	ms?: number;
	invalid?: string;
} {
	for (const [name, raw] of Object.entries(headers)) {
		if (name.toLowerCase() !== "grpc-timeout") continue;
		const value = typeof raw === "string" ? raw : raw[0];
		if (value === undefined) return {};
		const match = TIMEOUT.exec(value);
		const amount = match?.[1];
		const unit = TIMEOUT_UNIT_MS.get(match?.[2] ?? "");
		if (amount === undefined || unit === undefined) return { invalid: value };
		return { ms: Math.ceil(Number(amount) * unit) };
	}
	return {};
}

interface Route {
	method: DescMethod;
	run: (request: Message, context: GrpcContext) => unknown;
	interceptors: readonly GrpcInterceptor[];
}

export interface GrpcServicesOptions {
	/**
	 * Told about every error a method throws that is not a {@link GrpcError}
	 * — the ones the client only sees as INTERNAL. Default: `console.error`.
	 */
	onError?: (error: unknown, call: { path: string }) => void;
	/**
	 * Keep the fields of a request its schema does not know. Default: `false`
	 * — unlike a plain {@link Protobuf.decode}: each one costs an object, so a
	 * 4 MiB request of two-byte unknown fields would hold ~300 MB, and the
	 * reply is built from the method's return value anyway, never from the
	 * request. Turn it on for a method that forwards its request elsewhere.
	 */
	keepUnknownFields?: boolean;
	/**
	 * The largest request message accepted, in bytes; a larger one is
	 * answered RESOURCE_EXHAUSTED before any interceptor runs. `-1` for no
	 * limit. Default: 4 MiB.
	 */
	maxReceiveMessageLength?: number;
	/**
	 * The largest reply message sent, in bytes; a method whose reply is larger
	 * is answered RESOURCE_EXHAUSTED instead. Default: `-1`, no limit.
	 */
	maxSendMessageLength?: number;
	/**
	 * The most request bytes this server decodes and holds at once, summed over
	 * every call whose method has not settled yet; a call that would go past it
	 * is answered RESOURCE_EXHAUSTED before any interceptor runs or any byte is
	 * decoded. A call is always admitted when nothing else is in flight, so
	 * one message up to `maxReceiveMessageLength` is still served.
	 *
	 * The per-message limit alone does not bound memory: a decoded request is
	 * much larger than its bytes — every element of a repeated message field
	 * becomes a full object, ~70 bytes of heap per wire byte for a request of
	 * empty elements — and nothing else limits how many calls are decoded at
	 * once. A call answered DEADLINE_EXCEEDED or CANCELLED keeps its bytes
	 * counted until its method stops, since the method still holds its request.
	 * `-1` for no limit. Default: 8 MiB (two maximal requests).
	 */
	maxInFlightRequestBytes?: number;
}

const DEFAULT_MAX_RECEIVE_MESSAGE_LENGTH = 4 * 1024 * 1024;
const DEFAULT_MAX_IN_FLIGHT_REQUEST_BYTES = 8 * 1024 * 1024;

/** A byte count, or `-1` for none: anything else is a configuration error. */
function messageLimit(
	name: string,
	value: number | undefined,
	fallback: number,
): number {
	if (value === undefined) return fallback;
	if (!Number.isSafeInteger(value) || value < -1) {
		throw new NeutrinoError(
			"E_NEUTRINO_INVALID_OPTION",
			`Neutrino: ${name} must be a whole number of bytes, or -1 for no limit — got ${value}`,
		);
	}
	return value;
}

/** Whether `length` is past `limit` (`-1`: never). */
function exceeds(length: number, limit: number): boolean {
	return limit !== -1 && length > limit;
}

export class GrpcServices {
	readonly #protobuf: Protobuf;
	readonly #routes = new Map<string, Route>();
	readonly #services = new Set<string>();
	readonly #interceptors: GrpcInterceptor[] = [];
	readonly #onError: (error: unknown, call: { path: string }) => void;
	readonly #keepUnknownFields: boolean;
	readonly #maxReceive: number;
	readonly #maxSend: number;
	readonly #maxInFlight: number;
	/** Request bytes of the calls whose method has not settled yet. */
	#inFlight = 0;

	constructor(protobuf: Protobuf, options: GrpcServicesOptions = {}) {
		this.#protobuf = protobuf;
		this.#keepUnknownFields = options.keepUnknownFields ?? false;
		this.#maxReceive = messageLimit(
			"maxReceiveMessageLength",
			options.maxReceiveMessageLength,
			DEFAULT_MAX_RECEIVE_MESSAGE_LENGTH,
		);
		this.#maxSend = messageLimit(
			"maxSendMessageLength",
			options.maxSendMessageLength,
			-1,
		);
		this.#maxInFlight = messageLimit(
			"maxInFlightRequestBytes",
			options.maxInFlightRequestBytes,
			DEFAULT_MAX_IN_FLIGHT_REQUEST_BYTES,
		);
		this.#onError =
			options.onError ??
			((error, call) => console.error(`[grpc] ${call.path} failed`, error));
	}

	/**
	 * Run an interceptor around every call to every service, registered
	 * before or after. Interceptors run in the order they are added. A call to
	 * a method nobody serves is answered UNIMPLEMENTED without running any.
	 */
	use(interceptor: GrpcInterceptor): this {
		this.#interceptors.push(interceptor);
		return this;
	}

	/**
	 * Serve a service. Refused, at registration: a function-valued key that is
	 * not one of the service's methods (a typo would otherwise answer
	 * UNIMPLEMENTED forever) — an object's own or, for a class instance, one
	 * of its class's or a base class's methods, so a helper a class keeps
	 * belongs in a `#private` method — a method implemented by something that
	 * is not a function, a streaming method, and a service registered twice.
	 */
	service<S extends DescService>(
		service: S,
		impl: ServiceImpl<S>,
		options: ServiceOptions = {},
	): this {
		const interceptors = [...(options.interceptors ?? [])];
		if (this.#services.has(service.typeName)) {
			throw new NeutrinoError(
				"E_NEUTRINO_DUPLICATE_SERVICE",
				`Neutrino: service "${service.typeName}" is already registered`,
			);
		}
		const names = new Set(service.methods.map((method) => method.localName));
		for (const key of functionNamesOf(impl)) {
			if (!names.has(key)) {
				throw new UnknownMethodError(`/${service.typeName}/${key}`);
			}
		}

		const routes: [string, Route][] = [];
		for (const method of service.methods) {
			const implementation = implementationOf(impl, method.localName);
			if (implementation === undefined) continue;
			const path = `/${service.typeName}/${method.name}`;
			if (!isCallable(implementation)) {
				throw new NeutrinoError(
					"E_NEUTRINO_INVALID_IMPLEMENTATION",
					`Neutrino: the implementation of "${path}" is not a function`,
				);
			}
			if (method.methodKind !== "unary") {
				throw new NeutrinoError(
					"E_NEUTRINO_STREAMING_UNSUPPORTED",
					`Neutrino: ${method.methodKind} method "${path}" cannot be served yet — unary only`,
				);
			}
			// Called on the implementation, which reads its dependencies off
			// `this` when it is a class instance.
			routes.push([
				path,
				{
					method,
					run: (request, context) =>
						implementation.call(impl, request, context),
					interceptors,
				},
			]);
		}
		this.#services.add(service.typeName);
		for (const [path, route] of routes) this.#routes.set(path, route);
		return this;
	}

	/** Serve one call: the function handed to the host's server. */
	readonly handle = async (call: GrpcCall): Promise<GrpcReply> => {
		const route = this.#routes.get(call.path);
		if (!route) {
			return {
				code: GrpcStatus.UNIMPLEMENTED,
				details: `Method ${call.path} is not implemented`,
			};
		}
		if (exceeds(call.message.length, this.#maxReceive)) {
			return {
				code: GrpcStatus.RESOURCE_EXHAUSTED,
				details: `Received message larger than max (${call.message.length} vs ${this.#maxReceive})`,
			};
		}
		const timeout = timeoutOf(call.metadata);
		if (timeout.invalid !== undefined) {
			return {
				code: GrpcStatus.INTERNAL,
				details: `Invalid grpc-timeout value "${timeout.invalid}"`,
			};
		}
		let metadata: GrpcMetadata;
		try {
			metadata = new GrpcMetadata(call.metadata);
		} catch (error) {
			if (!(error instanceof InvalidMetadataError)) throw error;
			return { code: GrpcStatus.INTERNAL, details: error.message };
		}
		if (call.signal?.aborted === true) {
			return { code: GrpcStatus.CANCELLED, details: "Cancelled" };
		}
		if (timeout.ms === 0) {
			return {
				code: GrpcStatus.DEADLINE_EXCEEDED,
				details: "Deadline exceeded",
			};
		}
		if (
			this.#inFlight > 0 &&
			exceeds(this.#inFlight + call.message.length, this.#maxInFlight)
		) {
			return {
				code: GrpcStatus.RESOURCE_EXHAUSTED,
				details: `Too many request bytes in flight (${this.#maxInFlight} max)`,
			};
		}

		const controller = new AbortController();
		const context: GrpcContext = {
			metadata,
			ip: call.ip,
			method: route.method,
			deadline:
				timeout.ms === undefined
					? Number.POSITIVE_INFINITY
					: Date.now() + timeout.ms,
			signal: controller.signal,
		};
		// Answered as soon as the deadline passes or the client goes away;
		// the method is told through its signal and whatever it does next is
		// not waited for.
		// The executor runs at once, so `end` is set before anything calls it.
		let end: ((reply: GrpcReply) => void) | undefined;
		const ended = new Promise<GrpcReply>((resolve) => {
			end = resolve;
		});
		const stop = (code: GrpcStatusCode, details: string) => {
			if (controller.signal.aborted) return;
			controller.abort(new GrpcError(code, details));
			end?.({ code, details });
		};
		const timer =
			timeout.ms !== undefined && timeout.ms <= MAX_TIMER_MS
				? setTimeout(
						() => stop(GrpcStatus.DEADLINE_EXCEEDED, "Deadline exceeded"),
						timeout.ms,
					)
				: undefined;
		const cancel = () => stop(GrpcStatus.CANCELLED, "Cancelled");
		call.signal?.addEventListener("abort", cancel, { once: true });
		try {
			// Counted until the method settles, not until the call is answered:
			// a call answered at its deadline still holds its decoded request.
			const size = call.message.length;
			this.#inFlight += size;
			const serving = this.#serve(call, route, context);
			const release = () => {
				this.#inFlight -= size;
			};
			serving.then(release, release);
			return await Promise.race([serving, ended]);
		} finally {
			clearTimeout(timer);
			call.signal?.removeEventListener("abort", cancel);
		}
	};

	/** Run the interceptors and the method, and encode what they answer. */
	async #serve(
		call: GrpcCall,
		route: Route,
		context: GrpcContext,
	): Promise<GrpcReply> {
		const { method, run } = route;
		const chain = [...this.#interceptors, ...route.interceptors];

		// The method itself: decode, run, check what it returned. Innermost, so
		// an interceptor that refuses the call keeps its bytes from being read.
		const invoke = async (): Promise<Record<string, unknown>> => {
			if (context.signal.aborted) {
				// Its reason is the GrpcError the call was answered with.
				const reason: unknown = context.signal.reason;
				throw reason;
			}
			let request: Message;
			try {
				request = this.#protobuf.decode(method.input, call.message, {
					readUnknownFields: this.#keepUnknownFields,
				});
			} catch {
				// decode reports every malformed input the same way.
				throw new GrpcError(
					GrpcStatus.INVALID_ARGUMENT,
					`The request is not a valid ${method.input.typeName}`,
				);
			}
			const reply = await run(request, context);
			if (!isRecord(reply)) {
				throw new TypeError(
					`${call.path} returned ${reply === null ? "null" : typeof reply}, not a ${method.output.typeName}`,
				);
			}
			return reply;
		};

		let reached = -1;
		const step = async (index: number): Promise<unknown> => {
			if (index <= reached) {
				throw new Error(
					`An interceptor of ${call.path} called next() more than once`,
				);
			}
			reached = index;
			const interceptor = chain[index];
			if (interceptor === undefined) return invoke();
			return interceptor(context, () => step(index + 1));
		};

		try {
			const reply = await step(0);
			if (!isRecord(reply)) {
				throw new TypeError(
					`An interceptor of ${call.path} returned ${reply === null ? "null" : typeof reply} instead of what next() gave it`,
				);
			}
			const message = this.#protobuf.encode(
				method.output,
				create(method.output, reply),
			);
			if (exceeds(message.length, this.#maxSend)) {
				return {
					code: GrpcStatus.RESOURCE_EXHAUSTED,
					details: `Sent message larger than max (${message.length} vs. ${this.#maxSend})`,
				};
			}
			return { message };
		} catch (error) {
			if (error instanceof GrpcError) {
				return { code: error.status, details: error.message };
			}
			// Already answered DEADLINE_EXCEEDED or CANCELLED: what a method
			// throws while it stops is not a failure to report.
			if (!context.signal.aborted) this.#onError(error, { path: call.path });
			return { code: GrpcStatus.INTERNAL, details: "Internal error" };
		}
	}
}
