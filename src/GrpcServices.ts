/**
 * gRPC services implemented in TypeScript.
 *
 *   grpc.service(EchoService, {
 *     async say(request, context) {
 *       return { text: request.text.repeat(request.times) }
 *     },
 *   })
 *
 * Registered services are served by {@link GrpcServices.handle}, the function
 * the host's server calls for every gRPC call — in a Ream application,
 * `server.grpc(...)`, which the provider wires. Each call arrives as bytes:
 * the request is decoded with the method's input schema, the reply encoded
 * with its output schema.
 *
 * Unary methods only, for now: a service whose implementation names a
 * streaming method is refused when it is registered, and a call to a
 * streaming method answers UNIMPLEMENTED.
 */

import {
	create,
	type DescMethod,
	type DescService,
	type Message,
	type MessageInitShape,
	type MessageShape,
} from "@bufbuild/protobuf";
import { NeutrinoError, UnknownMethodError } from "./errors.js";
import type { Protobuf } from "./Protobuf.js";

/** gRPC status codes. */
export const GrpcStatus = {
	OK: 0,
	CANCELLED: 1,
	UNKNOWN: 2,
	INVALID_ARGUMENT: 3,
	DEADLINE_EXCEEDED: 4,
	NOT_FOUND: 5,
	ALREADY_EXISTS: 6,
	PERMISSION_DENIED: 7,
	RESOURCE_EXHAUSTED: 8,
	FAILED_PRECONDITION: 9,
	ABORTED: 10,
	OUT_OF_RANGE: 11,
	UNIMPLEMENTED: 12,
	INTERNAL: 13,
	UNAVAILABLE: 14,
	DATA_LOSS: 15,
	UNAUTHENTICATED: 16,
} as const;

export type GrpcStatusCode = (typeof GrpcStatus)[keyof typeof GrpcStatus];

/**
 * Thrown by a method implementation to answer a status instead of a reply.
 * Its message is sent to the client as the status details; any other error
 * is answered INTERNAL and its message is NOT sent.
 */
export class GrpcError extends NeutrinoError {
	readonly status: GrpcStatusCode;

	constructor(status: GrpcStatusCode, message: string, options?: ErrorOptions) {
		super("E_NEUTRINO_GRPC_STATUS", message, options);
		this.status = status;
	}
}

/** One call as the host's server hands it over. */
export interface GrpcCall {
	/** `/package.Service/Method`. */
	path: string;
	/** Request metadata, header names lowercased. */
	metadata: Record<string, string>;
	/** The request message, still encoded. */
	message: Uint8Array;
	/** Resolved client IP. */
	ip: string;
}

/** A reply message, encoded — or a status instead of one. */
export type GrpcReply =
	| { message: Uint8Array }
	| { code: number; details: string };

/** What a method implementation receives beside the request. */
export interface GrpcContext {
	/** Request metadata — `authorization` and the like — names lowercased. */
	readonly metadata: Readonly<Record<string, string>>;
	/** Resolved client IP. */
	readonly ip: string;
	/** The method being called. */
	readonly method: DescMethod;
}

/**
 * A method's implementation. A generated method carries its kind as a
 * literal, so a streaming one gets `never`; a method from a descriptor set
 * carries the union of kinds and stays implementable — registration then
 * checks the kind at runtime.
 */
type UnaryImpl<M> = M extends {
	methodKind: infer Kind;
	input: infer I extends DescMethod["input"];
	output: infer O extends DescMethod["output"];
}
	? "unary" extends Kind
		? (
				request: MessageShape<I>,
				context: GrpcContext,
			) => Promise<MessageInitShape<O>> | MessageInitShape<O>
		: never
	: never;

/**
 * The implementation of a service: one function per method, keyed by the
 * method's local name (`say` for `rpc Say`) — an object literal or a class
 * instance. A method left out answers UNIMPLEMENTED. With a service
 * generated by `protoc-gen-es`, requests and replies are typed from the
 * `.proto`; with one from a descriptor set, nothing is known about its
 * methods until runtime, so any object is accepted and registration checks it.
 */
export type ServiceImpl<S extends DescService> =
	string extends keyof S["method"]
		? // The record gives an object literal's functions their parameter
			// types; `object` admits a class instance, which has no index
			// signature to match the record with.
			Partial<Record<string, UntypedMethod>> | object
		: { [K in keyof S["method"]]?: UnaryImpl<S["method"][K]> };

/** A method of a service known only from a descriptor set. */
export type UntypedMethod = (
	request: Message,
	context: GrpcContext,
) => Promise<Record<string, unknown>> | Record<string, unknown>;

/** A function, called with arguments it is not told the types of. */
function isCallable(
	value: unknown,
): value is (this: unknown, ...args: unknown[]) => unknown {
	return typeof value === "function";
}

function isRecord(value: unknown): value is Record<string, unknown> {
	return typeof value === "object" && value !== null;
}

interface Route {
	method: DescMethod;
	run: (request: Message, context: GrpcContext) => unknown;
}

export interface GrpcServicesOptions {
	/**
	 * Told about every error a method throws that is not a {@link GrpcError}
	 * — the ones the client only sees as INTERNAL. Default: `console.error`.
	 */
	onError?: (error: unknown, call: { path: string }) => void;
}

export class GrpcServices {
	readonly #protobuf: Protobuf;
	readonly #routes = new Map<string, Route>();
	readonly #services = new Set<string>();
	readonly #onError: (error: unknown, call: { path: string }) => void;

	constructor(protobuf: Protobuf, options: GrpcServicesOptions = {}) {
		this.#protobuf = protobuf;
		this.#onError =
			options.onError ??
			((error, call) => console.error(`[grpc] ${call.path} failed`, error));
	}

	/**
	 * Serve a service. Refused, at registration: a function-valued key that is
	 * not one of the service's methods (a typo would otherwise answer
	 * UNIMPLEMENTED forever), a method implemented by something that is not a
	 * function, a streaming method, and a service registered twice.
	 */
	service<S extends DescService>(service: S, impl: ServiceImpl<S>): this {
		if (this.#services.has(service.typeName)) {
			throw new NeutrinoError(
				"E_NEUTRINO_DUPLICATE_SERVICE",
				`Neutrino: service "${service.typeName}" is already registered`,
			);
		}
		const names = new Set(service.methods.map((method) => method.localName));
		for (const [key, value] of Object.entries(impl)) {
			if (typeof value === "function" && !names.has(key)) {
				throw new UnknownMethodError(`/${service.typeName}/${key}`);
			}
		}

		const routes: [string, Route][] = [];
		for (const method of service.methods) {
			// Read through the prototype: a class instance keeps its methods
			// there, out of reach of Object.entries.
			const implementation: unknown = Reflect.get(impl, method.localName);
			if (implementation === undefined) continue;
			const path = `/${service.typeName}/${method.name}`;
			if (!isCallable(implementation)) {
				throw new NeutrinoError(
					"E_NEUTRINO_INVALID_IMPLEMENTATION",
					`Neutrino: the implementation of "${path}" is not a function`,
				);
			}
			if (method.methodKind !== "unary") {
				throw new NeutrinoError(
					"E_NEUTRINO_STREAMING_UNSUPPORTED",
					`Neutrino: ${method.methodKind} method "${path}" cannot be served yet — unary only`,
				);
			}
			// Called on the implementation, which reads its dependencies off
			// `this` when it is a class instance.
			routes.push([
				path,
				{
					method,
					run: (request, context) =>
						implementation.call(impl, request, context),
				},
			]);
		}
		this.#services.add(service.typeName);
		for (const [path, route] of routes) this.#routes.set(path, route);
		return this;
	}

	/** Serve one call: the function handed to the host's server. */
	readonly handle = async (call: GrpcCall): Promise<GrpcReply> => {
		const route = this.#routes.get(call.path);
		if (!route) {
			return {
				code: GrpcStatus.UNIMPLEMENTED,
				details: `Method ${call.path} is not implemented`,
			};
		}
		const { method, run } = route;

		let request: Message;
		try {
			request = this.#protobuf.decode(method.input, call.message);
		} catch {
			// decode reports every malformed input the same way.
			return {
				code: GrpcStatus.INVALID_ARGUMENT,
				details: `The request is not a valid ${method.input.typeName}`,
			};
		}

		try {
			const reply = await run(request, {
				metadata: call.metadata,
				ip: call.ip,
				method,
			});
			if (!isRecord(reply)) {
				throw new TypeError(
					`${call.path} returned ${reply === null ? "null" : typeof reply}, not a ${method.output.typeName}`,
				);
			}
			return {
				message: this.#protobuf.encode(
					method.output,
					create(method.output, reply),
				),
			};
		} catch (error) {
			if (error instanceof GrpcError) {
				return { code: error.status, details: error.message };
			}
			this.#onError(error, { path: call.path });
			return { code: GrpcStatus.INTERNAL, details: "Internal error" };
		}
	};
}
