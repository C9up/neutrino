import { readFileSync } from "node:fs";
import { create } from "@bufbuild/protobuf";
import { describe, expect, it } from "vitest";
import { GrpcServices, Protobuf } from "../src/index.js";
import {
	Echo,
	file_echo,
	SayReplySchema,
	SayRequestSchema,
} from "./fixtures/gen/echo_pb.js";

// fixtures/gen: protoc-gen-es 2.16.0 over tests/fixtures/echo.proto, with
//   protoc --es_out=gen --es_opt=target=ts,import_extension=js echo.proto shared/when.proto
// (buf generate gives the same files).
// tests/typed.check.ts holds what the compiler must accept and refuse.

describe("code generated by protoc-gen-es", () => {
	it("loads as a schema source and serves a typed service", async () => {
		const protobuf = new Protobuf({ files: [file_echo] });
		const grpc = new GrpcServices(protobuf).service(Echo, {
			say: (request) => ({ text: request.text.repeat(request.times) }),
		});
		const reply = await grpc.handle({
			path: "/echo.Echo/Say",
			metadata: {},
			ip: "127.0.0.1",
			message: protobuf.encode(
				SayRequestSchema,
				create(SayRequestSchema, { text: "ab", times: 2 }),
			),
		});
		if (!("message" in reply)) throw new Error(`status ${reply.code}`);
		expect(protobuf.decode(SayReplySchema, reply.message).text).toBe("abab");
	});

	it("agrees with the descriptor set compiled from the same .proto", () => {
		// An application may load generated files and a descriptor set built
		// from the same .proto; that must not read as two conflicting schemas.
		const protobuf = new Protobuf({
			files: [file_echo],
			descriptorSets: [
				readFileSync(new URL("./fixtures/echo.binpb", import.meta.url)),
			],
		});
		expect(protobuf.method("/echo.Echo/Say").input.typeName).toBe(
			"echo.SayRequest",
		);
	});

	it("agrees with a set built by buf, which keeps more than the schema", () => {
		// echo.buf.binpb: `buf build -o` over the same .proto. It carries the
		// positions and comments of the source and buf's image extension
		// (unknown field 8042), which protoc and protoc-gen-es leave out; none
		// of it says anything about the wire.
		expect(
			() =>
				new Protobuf({
					files: [file_echo],
					descriptorSets: [
						readFileSync(new URL("./fixtures/echo.buf.binpb", import.meta.url)),
					],
				}),
		).not.toThrow();
	});
});
